#!/usr/bin/env python3
"""Model tests; optionally verify against an existing Vision Pro core source tree.
Requires a JVM org.json implementation (Android supplies its own on device).
"""
import argparse, hashlib, os, shutil, subprocess, tempfile
from pathlib import Path
root=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--json-jar',type=Path,default=Path('/Applications/Android Studio.app/Contents/plugins/grazie/lib/org.json-json.jar'))
p.add_argument('--vision-core',type=Path,help='Directory containing Vision Pro SplativerseCore Swift sources')
a=p.parse_args()
java=Path(os.environ.get('JAVA_HOME','/Applications/Android Studio.app/Contents/jbr/Contents/Home'))/'bin'
build=root/'.build/library-tests';shutil.rmtree(build,ignore_errors=True);build.mkdir(parents=True)
def run(*args):subprocess.run([str(v) for v in args],check=True)
run(java/'javac','-source','8','-target','8','-Xlint:-options','-cp',a.json_jar,'-d',build,root/'app/src/main/java/com/splativerse/quest/LibraryStore.java',root/'tests/LibraryStoreTests.java',root/'app/src/main/java/com/splativerse/quest/SavedViewList.java',root/'tests/SavedViewListTests.java')
run(java/'java','-cp',str(build)+os.pathsep+str(a.json_jar),'com.splativerse.quest.SavedViewListTests')
work=build/'data';fixture=[]
if a.vision_core:
    run('swiftc','-O','-parse-as-library','-module-cache-path',build/'swift-cache',*sorted(a.vision_core.glob('*.swift')),root/'tests/vision_compatibility.swift','-o',build/'vision-compatibility')
    # Java Random(123)'s bytes are generated by the test, so have Java write them once.
    run(java/'java','-cp',str(build)+os.pathsep+str(a.json_jar),'com.splativerse.quest.LibraryStoreTests',build/'seed')
    digest=hashlib.sha256((build/'seed/renamed.splat').read_bytes()).hexdigest()
    run(build/'vision-compatibility','encode',digest,build/'vision.json');fixture=[build/'vision.json']
run(java/'java','-cp',str(build)+os.pathsep+str(a.json_jar),'com.splativerse.quest.LibraryStoreTests',work,*fixture)
if a.vision_core:run(build/'vision-compatibility','decode',work/'compat/viewpoints.json',work/'quest-settings.json')
